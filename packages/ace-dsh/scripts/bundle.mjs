#!/usr/bin/env node
/**
 * Build the installable artifact: one ESM file with everything but the host.
 *
 * The plugin is installed into a profile as a linked local directory, and pnpm does not install a linked
 * package's dependencies. Two things follow, and this script is both of them:
 *
 * - **`redis` and `typebox` are bundled in.** The core's transports need a broker client, `typebox` raises
 *   the core's tool schemas at module load, and neither is resolvable from a profile (`redis` is not in
 *   `$DSH_HOME/profiles/node_modules`). Bundling them means the installed plugin has no dependencies at all.
 * - **`@deepseek-ai/*` stays external.** Those are the host's own packages: the plugin must use the copies
 *   the running application provides — a second copy in the package would be a different module instance and
 *   a version the host does not have.
 *
 * Output: `lib/index.js` (what `main` points at) and `dist-package/` (the slim directory to install).
 */

import { build } from "esbuild";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

const result = await build({
	entryPoints: [join(root, "src", "index.ts")],
	outfile: join(root, "lib", "index.js"),
	bundle: true,
	platform: "node",
	format: "esm",
	target: "node22",
	sourcemap: true,
	logLevel: "warning",
	// The host's own packages: never bundled, never duplicated. Node built-ins stay external too — the
	// broker client is CommonJS in places and reaches for `node:crypto` at load time.
	external: ["@deepseek-ai/*", "node:*"],
	// `redis` is CommonJS: bundling it into ESM leaves its `require()` calls pointing at a shim that throws.
	// A real `require` for this file is what those calls need.
	banner: {
		js: [
			"// ace-dsh — generated by scripts/bundle.mjs; edit src/ and rebuild.",
			'import { createRequire as __aceCreateRequire } from "node:module";',
			"const require = __aceCreateRequire(import.meta.url);",
		].join("\n"),
	},
});

if (result.warnings.length > 0) {
	for (const warning of result.warnings) console.warn(`[bundle] warning: ${warning.text}`);
}

// The browser half is not bundled by esbuild: the client runtime loads it through `__ModuleLoader__.load`,
// which is the contract every client plugin follows (the skins in this workspace do the same). It is a
// wrapper around `src/client.js` verbatim, so the file that runs in the browser is the file that is read here.
const clientBody = await readFile(join(root, "src", "client.js"), "utf8");
if (clientBody.includes("</script")) throw new Error("src/client.js contains </script>");
const clientBundle = `window.__ModuleLoader__.load({
\tid: ${JSON.stringify(manifest.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

${clientBody}
\t\treturn module.exports;
\t}
});
`;
await writeFile(join(root, "lib", "client.js"), clientBundle);

// The install directory is deliberately minimal: a manifest with no dependencies, the Cordis patch that
// inserts the entry, and the two bundles. Nothing here can drift from the profile's own resolution.
const out = join(root, "dist-package");
await rm(out, { recursive: true, force: true });
await mkdir(join(out, "lib"), { recursive: true });
await cp(join(root, "lib", "index.js"), join(out, "lib", "index.js"));
await cp(join(root, "lib", "client.js"), join(out, "lib", "client.js"));
await cp(join(root, "cordis.patch.yml"), join(out, "cordis.patch.yml"));
await writeFile(
	join(out, "package.json"),
	`${JSON.stringify(
		{
			name: manifest.name,
			version: manifest.version,
			description: manifest.description,
			type: "module",
			main: "lib/index.js",
			exports: {
				".": "./lib/index.js",
				"./client": "./lib/client.js",
				"./package.json": "./package.json",
				"./cordis.patch.yml": "./cordis.patch.yml",
			},
			dsh: manifest.dsh,
			peerDependencies: manifest.peerDependencies,
			files: ["lib", "cordis.patch.yml", "README.md"],
			license: manifest.license,
		},
		null,
		"\t",
	)}\n`,
);
await cp(join(root, "README.md"), join(out, "README.md"));

console.log(
	`[bundle] ${manifest.name}@${manifest.version} → lib/index.js + lib/client.js (${Buffer.byteLength(clientBundle, "utf8")} bytes) + dist-package/`,
);
